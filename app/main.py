"""
Dharwad Kannada speech & translation API.

All four models live on the server (GPU), so clients only send text or audio:

  POST /speak          English speech (audio file)  -> English, Kannada, Dharwad text + Dharwad speech
  POST /translate/en   English text                 -> Kannada + Dharwad text
  POST /translate      standard Kannada text        -> Dharwad text
  POST /tts            Kannada / Dharwad text       -> speech (audio/wav)
  GET  /health         per-model status
  GET  /ping           RunPod Serverless probe: 204 while loading, 200 when ready
  GET  /metrics        Prometheus metrics
  GET  /docs           interactive Swagger UI (auto-generated by FastAPI)
  GET  /               browser UI: record with the browser mic, hear the answer (nothing to install)

Design
  * Every model is loaded ONCE, in a background thread at startup; endpoints return 503
    until the models they need are ready.
  * One lock per model: requests can overlap across stages but never share a model.
  * JSON logs carry sizes and per-stage latency only, never the text or audio
    (user content may contain personal data).
  * MOCK_MODEL=1 swaps every model for a fake, so tests/CI run without a GPU.
"""

import base64
import json
import logging
import os
import sys
import threading
import time
import uuid
from contextlib import asynccontextmanager
from pathlib import Path
from typing import Optional

from fastapi import Depends, FastAPI, File, Form, Header, HTTPException, Request, Response, UploadFile
from fastapi.responses import HTMLResponse
from prometheus_client import CONTENT_TYPE_LATEST, Counter, Histogram, generate_latest
from pydantic import BaseModel, Field, model_validator

from app.pipeline import MOCK, build_stages

# --------------------------------------------------------------------------- #
# Config (environment variables only - nothing secret in code)
# --------------------------------------------------------------------------- #
API_KEY = os.getenv("API_KEY")  # if set, clients must send "Authorization: Bearer <API_KEY>"
ENABLE_VOICE = os.getenv("ENABLE_VOICE", "1") == "1"  # 0 = text-only (Dharwad model only)
MAX_CHARS = int(os.getenv("MAX_CHARS", "1000"))
MAX_BATCH = int(os.getenv("MAX_BATCH", "16"))
MAX_AUDIO_MB = float(os.getenv("MAX_AUDIO_MB", "10"))
MAX_AUDIO_SECONDS = float(os.getenv("MAX_AUDIO_SECONDS", "60"))

STAGES = build_stages(ENABLE_VOICE)


# --------------------------------------------------------------------------- #
# Structured JSON logging
# --------------------------------------------------------------------------- #
class JsonFormatter(logging.Formatter):
    def format(self, record):
        payload = {"ts": round(time.time(), 3), "level": record.levelname, "msg": record.getMessage()}
        payload.update(getattr(record, "extra_fields", {}))
        return json.dumps(payload, ensure_ascii=False)


_handler = logging.StreamHandler(sys.stdout)
_handler.setFormatter(JsonFormatter())
log = logging.getLogger("dharwad")
log.handlers = [_handler]
log.setLevel(logging.INFO)
log.propagate = False


def log_event(msg: str, **fields):
    log.info(msg, extra={"extra_fields": fields})


# --------------------------------------------------------------------------- #
# Metrics
# --------------------------------------------------------------------------- #
REQUESTS = Counter("api_requests_total", "Requests", ["endpoint", "status"])
LATENCY = Histogram("api_latency_seconds", "End-to-end latency", ["endpoint"],
                    buckets=(0.1, 0.25, 0.5, 1, 2, 4, 8, 16, 32, 64))
STAGE_LATENCY = Histogram("stage_latency_seconds", "Per-model latency", ["stage"],
                          buckets=(0.05, 0.1, 0.25, 0.5, 1, 2, 4, 8, 16, 32))


# --------------------------------------------------------------------------- #
# Startup: load models in the background
# --------------------------------------------------------------------------- #
def _load_all():
    for name, stage in STAGES.items():  # dialect model first
        stage.load()
        log_event("model_loaded" if stage.ready else "model_load_failed", stage=name, **stage.status())


@asynccontextmanager
async def lifespan(app: FastAPI):
    threading.Thread(target=_load_all, daemon=True).start()
    yield


app = FastAPI(title="Dharwad Kannada Speech & Translation API", version="2.0.0", lifespan=lifespan)


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def check_api_key(authorization: Optional[str] = Header(None)):
    if API_KEY and authorization != f"Bearer {API_KEY}":
        raise HTTPException(status_code=401, detail="invalid or missing API key")


def require(endpoint: str, *names: str):
    for n in names:
        st = STAGES.get(n)
        if st is None:
            REQUESTS.labels(endpoint, "disabled").inc()
            raise HTTPException(status_code=404, detail=f"'{n}' is disabled on this server (ENABLE_VOICE=0)")
        if not st.ready:
            REQUESTS.labels(endpoint, "not_ready").inc()
            raise HTTPException(status_code=503, detail=st.error or f"model '{n}' is loading, retry shortly")


def timed(name: str, timings: dict, *args):
    t0 = time.perf_counter()
    out = STAGES[name].run(*args)
    dt = time.perf_counter() - t0
    timings[name] = round(dt * 1000, 1)
    STAGE_LATENCY.labels(name).observe(dt)
    return out


def request_id(request: Request) -> str:
    return request.headers.get("x-request-id") or uuid.uuid4().hex[:12]


def finish(endpoint: str, rid: str, t0: float, timings: dict, **fields):
    total = time.perf_counter() - t0
    REQUESTS.labels(endpoint, "ok").inc()
    LATENCY.labels(endpoint).observe(total)
    log_event(f"{endpoint}_ok", request_id=rid, total_ms=round(total * 1000, 1), stages_ms=timings, **fields)
    return round(total * 1000, 1)


def fail(endpoint: str, rid: str, e: Exception):
    REQUESTS.labels(endpoint, "error").inc()
    log_event(f"{endpoint}_error", request_id=rid, error=f"{type(e).__name__}: {e}")
    raise HTTPException(status_code=500, detail=f"{endpoint} failed (request_id={rid})")


# --------------------------------------------------------------------------- #
# Schemas
# --------------------------------------------------------------------------- #
class TranslateRequest(BaseModel):
    text: Optional[str] = Field(None, min_length=1, max_length=MAX_CHARS)
    texts: Optional[list[str]] = Field(None, min_length=1, max_length=MAX_BATCH)

    @model_validator(mode="after")
    def exactly_one(self):
        if (self.text is None) == (self.texts is None):
            raise ValueError("send exactly one of 'text' or 'texts'")
        for t in self.texts or []:
            if not t.strip() or len(t) > MAX_CHARS:
                raise ValueError(f"each text must be non-empty and at most {MAX_CHARS} characters")
        return self


class TranslateResponse(BaseModel):
    translations: list[str]
    latency_ms: float
    request_id: str


class EnglishRequest(BaseModel):
    text: str = Field(..., min_length=1, max_length=MAX_CHARS)


class EnglishResponse(BaseModel):
    english: str
    kannada: str
    dharwad: str
    timings_ms: dict
    latency_ms: float
    request_id: str


class TTSRequest(BaseModel):
    text: str = Field(..., min_length=1, max_length=MAX_CHARS)


class SpeakResponse(BaseModel):
    english: str
    kannada: str
    dharwad: str
    audio_wav_base64: Optional[str] = None
    timings_ms: dict
    latency_ms: float
    request_id: str


# --------------------------------------------------------------------------- #
# Endpoints
# Sync `def` endpoints run in FastAPI's thread pool, so the event loop (and /ping)
# stays responsive while a model is busy.
# --------------------------------------------------------------------------- #
@app.post("/translate", response_model=TranslateResponse, dependencies=[Depends(check_api_key)])
def translate(req: TranslateRequest, request: Request):
    """Standard Kannada text -> Dharwad Kannada text."""
    rid, t0, timings = request_id(request), time.perf_counter(), {}
    require("translate", "dialect")
    texts = req.texts or [req.text]
    try:
        out = timed("dialect", timings, texts)
    except Exception as e:
        fail("translate", rid, e)
    total = finish("translate", rid, t0, timings, n=len(texts), input_chars=sum(map(len, texts)))
    return TranslateResponse(translations=out, latency_ms=total, request_id=rid)


@app.post("/translate/en", response_model=EnglishResponse, dependencies=[Depends(check_api_key)])
def translate_english(req: EnglishRequest, request: Request):
    """English text -> standard Kannada -> Dharwad Kannada."""
    rid, t0, timings = request_id(request), time.perf_counter(), {}
    require("translate_en", "en_kn", "dialect")
    try:
        kannada = timed("en_kn", timings, [req.text])[0]
        dharwad = timed("dialect", timings, [kannada])[0]
    except Exception as e:
        fail("translate_en", rid, e)
    total = finish("translate_en", rid, t0, timings, input_chars=len(req.text))
    return EnglishResponse(english=req.text, kannada=kannada, dharwad=dharwad,
                           timings_ms=timings, latency_ms=total, request_id=rid)


@app.post("/tts", dependencies=[Depends(check_api_key)],
          responses={200: {"content": {"audio/wav": {}}}})
def tts(req: TTSRequest, request: Request):
    """Kannada / Dharwad text -> speech (WAV)."""
    rid, t0, timings = request_id(request), time.perf_counter(), {}
    require("tts", "tts")
    try:
        audio = timed("tts", timings, req.text)
    except Exception as e:
        fail("tts", rid, e)
    total = finish("tts", rid, t0, timings, input_chars=len(req.text), audio_bytes=len(audio))
    return Response(audio, media_type="audio/wav",
                    headers={"X-Request-Id": rid, "X-Latency-Ms": str(total)})


@app.post("/speak", response_model=SpeakResponse, dependencies=[Depends(check_api_key)])
def speak(
    request: Request,
    audio: UploadFile = File(..., description="English speech: wav, mp3, m4a, ogg or webm"),
    tts: bool = Form(True, description="Also return Dharwad speech"),
):
    """English speech -> English text -> Kannada -> Dharwad Kannada (-> Dharwad speech)."""
    rid, t0, timings = request_id(request), time.perf_counter(), {}
    needed = ["asr", "en_kn", "dialect"] + (["tts"] if tts else [])
    require("speak", *needed)

    data = audio.file.read(int(MAX_AUDIO_MB * 1024 * 1024) + 1)
    if not data:
        raise HTTPException(status_code=422, detail="empty audio file")
    if len(data) > MAX_AUDIO_MB * 1024 * 1024:
        raise HTTPException(status_code=413, detail=f"audio larger than {MAX_AUDIO_MB} MB")

    try:
        samples = STAGES["asr"].decode(data)
    except Exception:
        raise HTTPException(status_code=422, detail="could not decode audio; send wav/mp3/m4a/ogg/webm")
    if samples is not None:
        seconds = len(samples) / 16_000
        if seconds < 0.3:
            raise HTTPException(status_code=422, detail="audio too short")
        if seconds > MAX_AUDIO_SECONDS:
            raise HTTPException(status_code=413, detail=f"audio longer than {MAX_AUDIO_SECONDS:.0f} s")

    try:
        english = timed("asr", timings, samples)
    except Exception as e:
        fail("speak", rid, e)
    if not english:
        REQUESTS.labels("speak", "no_speech").inc()
        raise HTTPException(status_code=422, detail="no speech recognised")

    try:
        kannada = timed("en_kn", timings, [english])[0]
        dharwad = timed("dialect", timings, [kannada])[0]
        wav = timed("tts", timings, dharwad) if tts else None
    except Exception as e:
        fail("speak", rid, e)

    total = finish("speak", rid, t0, timings, audio_in_bytes=len(data),
                   audio_out_bytes=len(wav) if wav else 0)
    return SpeakResponse(
        english=english, kannada=kannada, dharwad=dharwad,
        audio_wav_base64=base64.b64encode(wav).decode() if wav else None,
        timings_ms=timings, latency_ms=total, request_id=rid,
    )


INDEX_HTML = (Path(__file__).parent / "static" / "index.html").read_text(encoding="utf-8")


@app.get("/", response_class=HTMLResponse, include_in_schema=False)
def index():
    """Browser client: the user's browser captures the mic and plays the reply."""
    return INDEX_HTML


@app.get("/health")
def health():
    models = {name: st.status() for name, st in STAGES.items()}
    states = {m["status"] for m in models.values()}
    overall = "ok" if states == {"ok"} else ("error" if "error" in states else "loading")
    # Always 200 so a Pod's liveness check doesn't kill the container mid-download.
    return {"status": overall, "voice_enabled": ENABLE_VOICE, "mock": MOCK, "models": models}


@app.get("/ping")
def ping():
    # RunPod Serverless load balancer: 204 = initializing, 200 = ready
    if all(st.ready for st in STAGES.values()):
        return {"status": "healthy"}
    if any(st.error for st in STAGES.values()):
        return Response(status_code=503)
    return Response(status_code=204)


@app.get("/metrics")
def metrics():
    return Response(generate_latest(), media_type=CONTENT_TYPE_LATEST)
